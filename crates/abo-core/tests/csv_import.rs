//! Integration tests for the Phase 3 WizTree CSV import (F-102): AC-102.1,
//! AC-102.2, AC-102.3.
//!
//! `import_synthetic_csv_produces_valid_snapshot` runs on every OS (the CI
//! test job runs ubuntu + windows): it is pure text in, DB rows out, with no
//! dependency on the host's own path-separator convention (see
//! `crate::scan::csv_import`'s module doc). `import_parity_with_live_scan_of_
//! fixture_library` (AC-102.2) IS Windows-only: it round-trips a live scan's
//! OWN host-native paths through a constructed WizTree CSV, which is only a
//! meaningful comparison when those paths are the Windows-backslash form
//! WizTree itself always emits. `import_real_wiztree_2026_03_25_csv` is
//! `#[ignore]`d (the real file lives under `_local/`, never committed, so CI
//! never has it) and is run locally on demand: `cargo test -p abo-core
//! --test csv_import -- --ignored`.

use std::path::Path;

use abo_core::db::open_db;
use abo_core::scan::{get_scan_entries, run_csv_import};
use sqlx::SqlitePool;
use tempfile::TempDir;

/// A fresh, migrated database in its own temp dir (kept alive by the returned
/// `TempDir`), matching the `tests/scan.rs` convention.
async fn fresh_pool() -> (TempDir, SqlitePool) {
    let dir = TempDir::new().expect("db tempdir");
    let (pool, _) = open_db(dir.path()).await.expect("open_db");
    (dir, pool)
}

const PREAMBLE_AND_HEADER: &str =
    "Generated by WizTree 4.30 3/25/2026 8:54:06 AM (You can hide this message by making a donation)\r\n\
     File Name,Size,Allocated,Modified,Attributes,Files,Folders,FOLDERSIZE,FOLDERALLOCATED,DRIVECAPACITY,FREESPACE,USEDSPACE,RESERVEDSPACE\r\n";

/// AC-102.1: importing a small hand-built WizTree CSV produces a valid
/// snapshot flagged `source = csv` with parent linkage reconstructed from the
/// path column, sizes/kinds/classes/depths matching the CSV's contents.
#[tokio::test]
async fn import_synthetic_csv_produces_valid_snapshot() {
    let (_db, pool) = fresh_pool().await;
    let csv_dir = TempDir::new().expect("csv tempdir");
    let csv_path = csv_dir.path().join("sample.csv");

    let body = "\"E:\\Lib\\\",300,304,2026/01/01 00:00:00,0,3,1,300,304,100,100,100,100\r\n\
                \"E:\\Lib\\Sub\\\",200,204,2026/01/02 00:00:00,16,1,0,200,204\r\n\
                \"E:\\Lib\\root.m4b\",100,104,2026/01/03 00:00:00,32,0,0,100,104\r\n\
                \"E:\\Lib\\Sub\\nested.mp3\",200,204,2026/01/04 00:00:00,32,0,0,200,204\r\n\
                \"E:\\Lib\\cover.jpg\",50,52,2026/01/05 00:00:00,32,0,0,50,52\r\n";
    std::fs::write(&csv_path, format!("{PREAMBLE_AND_HEADER}{body}")).expect("write fixture csv");

    let summary = run_csv_import(&pool, &csv_path).await.expect("csv import");
    assert_eq!(summary.status, "completed");
    assert_eq!(summary.skipped_count, 0, "clean fixture skips nothing");
    assert_eq!(summary.entry_count, 5);
    assert_eq!(
        summary.total_bytes,
        100 + 200 + 50,
        "sum of the 3 file sizes"
    );
    assert_eq!(summary.root_path, r"E:\Lib");

    // The `scans` row is flagged `source = csv` (AC-102.1).
    let (source,): (String,) = sqlx::query_as("SELECT source FROM scans WHERE id = ?")
        .bind(summary.scan_id)
        .fetch_one(&pool)
        .await
        .expect("fetch source");
    assert_eq!(source, "csv");

    let entries = get_scan_entries(&pool, summary.scan_id)
        .await
        .expect("read entries");
    assert_eq!(entries.len(), 5);

    let by_name = |name: &str| {
        entries
            .iter()
            .find(|e| e.name == name)
            .unwrap_or_else(|| panic!("missing entry {name}"))
    };

    // Parent linkage reconstructed from the path column: exactly the root
    // lacks a parent, and every other entry's parent_id resolves to a real
    // row in the same snapshot (AC-102.1).
    let root = by_name("Lib");
    assert_eq!(root.kind, "dir");
    assert_eq!(root.depth, 0);
    assert_eq!(root.parent_id, None, "the root has no parent");
    assert!(root.file_class.is_none());

    let sub = by_name("Sub");
    assert_eq!(sub.kind, "dir");
    assert_eq!(sub.depth, 1);
    assert_eq!(sub.parent_id, Some(root.id));

    let root_file = by_name("root.m4b");
    assert_eq!(root_file.kind, "file");
    assert_eq!(root_file.file_class.as_deref(), Some("audio"));
    assert_eq!(root_file.size, 100);
    assert_eq!(root_file.parent_id, Some(root.id));

    let nested = by_name("nested.mp3");
    assert_eq!(nested.depth, 2);
    assert_eq!(nested.file_class.as_deref(), Some("audio"));
    assert_eq!(nested.parent_id, Some(sub.id));

    let cover = by_name("cover.jpg");
    assert_eq!(cover.file_class.as_deref(), Some("image"));
    assert_eq!(cover.parent_id, Some(root.id));

    let no_parent = entries.iter().filter(|e| e.parent_id.is_none()).count();
    assert_eq!(no_parent, 1, "only the root lacks a parent");
    let ids: std::collections::HashSet<i64> = entries.iter().map(|e| e.id).collect();
    for e in entries.iter().filter(|e| e.parent_id.is_some()) {
        assert!(
            ids.contains(&e.parent_id.unwrap()),
            "parent_id of {} must reference an entry in the snapshot",
            e.name
        );
    }
}

/// AC-102.3: a CSV with one malformed row still produces a snapshot for the
/// rest, and the caller-visible `skipped_count` reflects the one recovered
/// row (the row's exact index is unit-tested directly against
/// `parse_wiztree_csv` in `src/scan/csv_import.rs`).
#[tokio::test]
async fn import_recovers_from_one_malformed_row() {
    let (_db, pool) = fresh_pool().await;
    let csv_dir = TempDir::new().expect("csv tempdir");
    let csv_path = csv_dir.path().join("sample.csv");

    let body = "\"E:\\Lib\\\",300,304,2026/01/01 00:00:00,0,2,0,300,304,100,100,100,100\r\n\
                \"E:\\Lib\\good.mp3\",100,104,2026/01/02 00:00:00,32,0,0,100,104\r\n\
                \"E:\\Lib\\bad.mp3\",NOTANUMBER,104,2026/01/03 00:00:00,32,0,0,100,104\r\n";
    std::fs::write(&csv_path, format!("{PREAMBLE_AND_HEADER}{body}")).expect("write fixture csv");

    let summary = run_csv_import(&pool, &csv_path).await.expect("csv import");
    assert_eq!(summary.status, "completed");
    assert_eq!(
        summary.skipped_count, 1,
        "the one bad row is counted, not fatal"
    );
    assert_eq!(summary.entry_count, 2, "root + the one good file");

    let entries = get_scan_entries(&pool, summary.scan_id)
        .await
        .expect("read entries");
    assert!(entries.iter().any(|e| e.name == "good.mp3"));
    assert!(!entries.iter().any(|e| e.name == "bad.mp3"));
}

/// A wholly invalid file (no WizTree header at all) fails cleanly and writes
/// no `scans` row, mirroring `run_scan`'s bad-root posture.
#[tokio::test]
async fn import_wholly_invalid_file_writes_no_scan_row() {
    use abo_core::error::AppError;

    let (_db, pool) = fresh_pool().await;
    let csv_dir = TempDir::new().expect("csv tempdir");
    let csv_path = csv_dir.path().join("not-wiztree.csv");
    std::fs::write(&csv_path, "nope,not,a,wiztree,file\r\n").expect("write junk file");

    let result = run_csv_import(&pool, &csv_path).await;
    match result {
        Err(AppError::CsvParse { row: 0 }) => {}
        other => panic!("expected CsvParse{{row: 0}}, got {other:?}"),
    }

    let (count,): (i64,) = sqlx::query_as("SELECT COUNT(*) FROM scans")
        .fetch_one(&pool)
        .await
        .unwrap();
    assert_eq!(count, 0, "an invalid CSV writes no scans row");
}

