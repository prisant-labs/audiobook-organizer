// AC-102.2: parity between a live scan and a CSV import of an equivalent tree.
// ---------------------------------------------------------------------------

/// Convert the walker's ISO-8601 UTC mtime (`YYYY-MM-DDTHH:MM:SSZ`) back into
/// WizTree's `Modified` shape (`YYYY/MM/DD HH:MM:SS`), the reverse of
/// `crate::scan::csv_import::reformat_modified`. Test-only: only needs to
/// round-trip the exact shape the walker itself produces.
fn to_wiztree_modified(iso: &str) -> String {
    let date = &iso[0..10].replace('-', "/");
    let time = &iso[11..19];
    format!("{date} {time}")
}

/// Quote a `File Name` field WizTree-style (wrap in `"`; WizTree paths never
/// contain a literal `"`, so no escaping is needed for this test's fixtures).
fn quote(s: &str) -> String {
    format!("\"{s}\"")
}

/// AC-102.2: scan the P1 generated fixture library live, construct an
/// equivalent WizTree CSV from that exact snapshot's own entries, import it,
/// and compare the two entries tables (paths, kinds, sizes, depths, classes).
/// Windows-only: this constructs WizTree rows from the live scan's OWN
/// host-native paths, which is only a like-for-like comparison when those
/// paths are the Windows-backslash form WizTree always emits (see this file's
/// module doc and `crate::scan::csv_import`'s cross-platform-path section).
#[cfg(windows)]
#[tokio::test]
async fn import_parity_with_live_scan_of_fixture_library() {
    use abo_core::fixtures::{generate, standard_library_manifest};
    use abo_core::scan::run_scan;

    let (_db, pool) = fresh_pool().await;
    let tree = TempDir::new().expect("fixture tempdir");
    generate(&standard_library_manifest(), tree.path()).expect("generate fixtures");

    let live_summary = run_scan(&pool, tree.path()).await.expect("live scan");
    let live_entries = get_scan_entries(&pool, live_summary.scan_id)
        .await
        .expect("read live entries");

    // Build an equivalent WizTree CSV row for every entry the live scan
    // recorded, using that entry's own stored path verbatim (so the
    // reconstructed CSV-import path matches byte-for-byte).
    let mut body = String::new();
    for e in &live_entries {
        let name = if e.kind == "dir" {
            format!("{}\\", e.path)
        } else {
            e.path.clone()
        };
        let attrs = if e.kind == "dir" { 16 } else { 32 };
        // A directory's Size/Allocated are never read by the importer
        // (module doc quirk 4); a file's Size is what matters.
        let modified = e
            .mtime
            .as_deref()
            .map(to_wiztree_modified)
            .unwrap_or_else(|| "2026/01/01 00:00:00".to_string());
        body.push_str(&format!(
            "{},{},{},{},{},0,0,0,0\r\n",
            quote(&name),
            e.size,
            e.size,
            modified,
            attrs
        ));
    }
    let csv_dir = TempDir::new().expect("csv tempdir");
    let csv_path = csv_dir.path().join("equivalent.csv");
    std::fs::write(&csv_path, format!("{PREAMBLE_AND_HEADER}{body}")).expect("write csv");

    let csv_summary = run_csv_import(&pool, &csv_path).await.expect("csv import");
    assert_eq!(
        csv_summary.skipped_count, 0,
        "the constructed CSV is well-formed"
    );
    let csv_entries = get_scan_entries(&pool, csv_summary.scan_id)
        .await
        .expect("read csv entries");

    assert_eq!(
        csv_entries.len(),
        live_entries.len(),
        "the CSV import must recover the same entry count as the live scan"
    );

    // Compare by path (identical strings between the two snapshots by
    // construction): kind, size, depth, and class must agree. mtime and
    // allocated size are documented differences and are not compared (this
    // phase's brief; mtime precision, allocated size).
    use std::collections::HashMap;
    let by_path: HashMap<&str, &abo_core::ipc::EntryRow> =
        csv_entries.iter().map(|e| (e.path.as_str(), e)).collect();

    for live in &live_entries {
        let csv_e = by_path
            .get(live.path.as_str())
            .unwrap_or_else(|| panic!("csv import missing path {}", live.path));
        assert_eq!(csv_e.kind, live.kind, "kind mismatch for {}", live.path);
        assert_eq!(
            csv_e.file_class, live.file_class,
            "file_class mismatch for {}",
            live.path
        );
        assert_eq!(csv_e.size, live.size, "size mismatch for {}", live.path);
        assert_eq!(csv_e.depth, live.depth, "depth mismatch for {}", live.path);
    }
}

