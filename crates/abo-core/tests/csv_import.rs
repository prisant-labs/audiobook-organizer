/// AC-102.1 against the real rescued 2026-03-25 snapshot: importing it
/// produces a valid `source = csv` snapshot whose counts feed the P7 baseline
/// comparison (G-07). `#[ignore]`d because `_local/` is never committed, so a
/// CI runner never has this file; run locally with `--ignored`.
#[ignore = "reads the real, uncommitted _local/prior-work/WizTree_2026-03-25.csv; \
            run locally with `cargo test -p abo-core --test csv_import -- --ignored`"]
#[tokio::test]
async fn import_real_wiztree_2026_03_25_csv() {
    let path = real_csv_path();
    assert!(
        path.is_file(),
        "expected the real WizTree export at {}; this test only runs locally \
         where _local/prior-work/ is present",
        path.display()
    );

    let (_db, pool) = fresh_pool().await;
    let summary = run_csv_import(&pool, &path).await.expect("import real csv");

    assert_eq!(summary.status, "completed");
    assert_eq!(summary.root_path, r"E:\Books - Audio");

    let entries = get_scan_entries(&pool, summary.scan_id)
        .await
        .expect("read entries");
    let dirs = entries.iter().filter(|e| e.kind == "dir").count();
    let files = entries.iter().filter(|e| e.kind == "file").count();

    // Printed (not just asserted) so `cargo test -- --ignored --nocapture`
    // surfaces the numbers this phase's report pastes for the P7 baseline.
    println!(
        "real WizTree 2026-03-25 import: entry_count={} total_bytes={} \
         skipped_count={} dirs={} files={}",
        summary.entry_count, summary.total_bytes, summary.skipped_count, dirs, files
    );

    assert_eq!(
        summary.skipped_count, 0,
        "the real file has no malformed rows"
    );
    assert_eq!(summary.entry_count, 14689);
    assert_eq!(summary.total_bytes, 319_290_437_409);
    assert_eq!(dirs, 719);
    assert_eq!(files, 13970);
}
